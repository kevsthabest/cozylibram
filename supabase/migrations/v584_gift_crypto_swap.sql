-- ================= Gift a Book: crypto primitive swap (v584) =================
--
-- DECISION RECORD. v582 (A8) encrypted the gift address vault with
-- pgsodium's by-key-id AEAD, which requires the executing role to hold
-- the pgsodium_keyiduser membership. That membership can only be
-- granted by supabase_admin, and the grant proved UNREACHABLE through
-- every channel available to this project (all verified live,
-- 2026-10-15):
--   * sb-query / Management API (runs as postgres): 42501.
--   * Supabase dashboard SQL editor (also executes as postgres):
--     the same 42501, verbatim.
--   * SET ROLE supabase_admin from a postgres session: denied.
-- No user-facing channel runs as supabase_admin, so the pgsodium path
-- is a dead end in production: gift_enc/gift_dec raise on every call
-- and the feature fails closed with zero addresses stored.
--
-- THE SWAP. gift_enc/gift_dec keep their names, signatures, and
-- semantics; only their internals change, from pgsodium by-key-id
-- AEAD to pgcrypto symmetric PGP encryption:
--   * Cipher: AES-256 (cipher-algo=aes256).
--   * Integrity: the PGP modification-detection code (MDC) that
--     pgcrypto symmetric encryption carries by default (NOT disabled)
--     — a tampered or truncated ciphertext raises on decrypt instead
--     of yielding altered plaintext.
--   * Key derivation: S2K mode 3 (iterated + salted) with SHA-512,
--     deriving the working key from the Vault-held secret per call.
--   * Key material: 48 random bytes (extensions.gen_random_bytes),
--     base64-encoded, generated by THIS migration and stored via
--     vault.create_secret under the name 'gift-address-key-v1'. It
--     never appears in the repo, in SQL literals, or in any client;
--     the definer functions read it from vault.decrypted_secrets at
--     call time (verified readable by the definer owner in a
--     rolled-back transaction before this migration was finalized).
--   * Owner binding (A8's substance, preserved from v582's additional
--     data): the effective passphrase is the Vault secret joined with
--     the owner id, so a ciphertext copied onto another owner's row
--     fails the integrity check and decrypts to nothing (raises).
-- A8's requirement is unchanged and still met: column-level
-- encryption at build, keys in Supabase Vault, a database-level
-- exposure of gift_addresses yields ciphertext only. Only the
-- primitive named in A8 is substituted, because the platform made
-- the named one unusable; the substitution was approved by the User
-- on 2026-10-15.
--
-- WHY THE SWAP IS FREE: gift_addresses holds ZERO rows (verified
-- live at drafting). No ciphertext exists in the v582 format, so no
-- data migration or dual-read window is needed; values written after
-- this migration are pgcrypto-format only. (v582's nonce-packed
-- layout disappears with the functions that defined it.)
--
-- CLEANUP. The pgsodium vestiges v582 created are removed:
--   * public.gift_crypto (the key-id bookkeeping table) is dropped.
--   * The pgsodium EXTENSION is dropped. Verified live before
--     drafting: nothing outside gift_enc/gift_dec references pgsodium
--     anywhere in the database, and DROP EXTENSION succeeds without
--     CASCADE in a rolled-back transaction. Dropping it also disposes
--     of the orphaned 'gift-address-v1' key material in pgsodium's
--     own key table — no wrapped key is left behind for a primitive
--     nothing can execute.
-- pgcrypto is already installed on the project (extensions schema);
-- its functions are called schema-qualified because gift_enc/gift_dec
-- pin search_path = public (the same reason v582's unqualified
-- gen_random_bytes call could never have resolved — this migration
-- qualifies every pgcrypto call).
--
-- No client or RPC changes: gift_enc/gift_dec are internal helpers
-- (EXECUTE revoked from public/anon/authenticated, unchanged), and
-- every caller (gift_address_upsert/mine/reveal) goes through them.

-- ============================ the Vault key ============================
select vault.create_secret(
  encode(extensions.gen_random_bytes(48), 'base64'),
  'gift-address-key-v1',
  'Gift a Book address-vault encryption key (v584, pgcrypto). Read only by gift_enc/gift_dec via vault.decrypted_secrets.')
where not exists (select 1 from vault.secrets where name = 'gift-address-key-v1');

-- ====================== gift_enc / gift_dec (pgcrypto) ======================
create or replace function public.gift_enc(p_plain text, p_owner uuid)
returns bytea
language plpgsql
security definer
stable
set search_path = public
as $$
declare
  v_key text;
begin
  if p_plain is null then return null; end if;
  select decrypted_secret into v_key from vault.decrypted_secrets
    where name = 'gift-address-key-v1';
  if v_key is null then raise exception 'gift key not provisioned'; end if;
  return extensions.pgp_sym_encrypt(
    p_plain,
    v_key || ':' || p_owner::text,
    'cipher-algo=aes256, s2k-mode=3, s2k-digest-algo=sha512');
end;
$$;
revoke all on function public.gift_enc(text, uuid) from public, anon, authenticated;

create or replace function public.gift_dec(p_packed bytea, p_owner uuid)
returns text
language plpgsql
security definer
stable
set search_path = public
as $$
declare
  v_key text;
begin
  if p_packed is null then return null; end if;
  select decrypted_secret into v_key from vault.decrypted_secrets
    where name = 'gift-address-key-v1';
  if v_key is null then raise exception 'gift key not provisioned'; end if;
  return extensions.pgp_sym_decrypt(
    p_packed,
    v_key || ':' || p_owner::text);
end;
$$;
revoke all on function public.gift_dec(bytea, uuid) from public, anon, authenticated;

-- ============================ pgsodium cleanup ============================
drop table if exists public.gift_crypto;
drop extension if exists pgsodium;
