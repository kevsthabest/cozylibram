-- The giftable-format resolution for one of the owner's books, by the
-- canonical book key: the wishlist derivation (tbr + tobuy) first, then
-- trophy wants (owned book whose wantFormat differs from its format —
-- the js/000 isTrophyWant predicate). Returns the format KIND the gift
-- needs ('print' | 'ebook' | 'audio'), or null when the owner holds no
-- giftable copy under that key (never wanted it, or already acquired /
-- removed it — the serve-time release for claims reads through this).
create or replace function public.gift_book_format_kind(p_owner uuid, p_book_key text)
returns text
language sql
security definer
stable
set search_path = public
as $$
  select case
           when k.fmt in ('ebook') then 'ebook'
           when k.fmt in ('audio') then 'audio'
           else 'print'
         end
  from (
    select case
             when b.data ->> 'status' = 'tbr' and b.data ->> 'owned' = 'tobuy'
               then coalesce(nullif(b.data ->> 'format', ''), 'physical')
             else b.data ->> 'wantFormat'
           end as fmt,
           (b.data ->> 'status' = 'tbr' and b.data ->> 'owned' = 'tobuy') as derived
    from public.books b
    where b.user_id = p_owner
      and public.marginalia_book_key(b.data, b.isbn) = p_book_key
      and (
        (b.data ->> 'status' = 'tbr' and b.data ->> 'owned' = 'tobuy')
        or (
          b.data ->> 'format' in ('hardcover', 'paperback', 'physical', 'ebook', 'audio')
          and b.data ->> 'wantFormat' in ('hardcover', 'paperback', 'physical', 'ebook', 'audio')
          and b.data ->> 'wantFormat' <> b.data ->> 'format'
          and not (b.data ->> 'status' = 'tbr' and b.data ->> 'owned' = 'tobuy')
        )
      )
  ) k
  order by k.derived desc
  limit 1;
$$;
revoke all on function public.gift_book_format_kind(uuid, text) from public, anon, authenticated;

-- Serve-time liveness for a stored claim (spec A7). A claim is live
-- only while ALL of these hold right now: stored state still 'active';
-- younger than 45 days; the recipient's grant to the claimer stands
-- AND is the same grant instance the claim was made under (a grant
-- row created after the claim is a re-grant, and re-granting never
-- resurrects a claim — the friend claims again); the pair is still
-- linked; no block either way; the wishlist is not hidden; and the
-- recipient still holds the book as a giftable want.
create or replace function public.gift_claim_is_live(p_claim uuid)
returns boolean
language plpgsql
security definer
stable
set search_path = public
as $$
declare
  c public.gift_claims%rowtype;
begin
  select * into c from public.gift_claims where id = p_claim;
  if not found or c.state <> 'active' then return false; end if;
  if now() >= c.created_at + interval '45 days' then return false; end if;
  if not exists (
    select 1 from public.gift_grants g
    where g.recipient_id = c.recipient_id and g.friend_id = c.claimer_id
      and g.created_at <= c.created_at
  ) then return false; end if;
  if not public.gift_pair_linked(c.recipient_id, c.claimer_id) then return false; end if;
  if public.gift_pair_blocked(c.recipient_id, c.claimer_id) then return false; end if;
  if not public.gift_wishlist_open(c.recipient_id) then return false; end if;
  if public.gift_book_format_kind(c.recipient_id, c.book_key) is null then return false; end if;
  return true;
end;
$$;
revoke all on function public.gift_claim_is_live(uuid) from public, anon, authenticated;

-- The composed state every read surface reports for a claim: stored
-- resolutions are final; a stored 'active' claim reads 'active' only
-- while live, 'expired' once its 45 days have run, else 'released'.
create or replace function public.gift_claim_state(p_claim uuid)
returns text
language plpgsql
security definer
stable
set search_path = public
as $$
declare
  c public.gift_claims%rowtype;
begin
  select * into c from public.gift_claims where id = p_claim;
  if not found then return 'released'; end if;
  if c.state in ('purchased', 'released') then return c.state; end if;
  if public.gift_claim_is_live(c.id) then return 'active'; end if;
  if now() >= c.created_at + interval '45 days' then return 'expired'; end if;
  return 'released';
end;
$$;
revoke all on function public.gift_claim_state(uuid) from public, anon, authenticated;

-- ============================ claim RPCs ============================

-- Create the caller's claim on one of the recipient's wishlist books.
-- Every refusal — no grant, no link, blocked, hidden wishlist, book
-- not giftable, already claimed, claimer cap — returns the identical
-- {ok:false}. Success is the claimer's own data, so it may be full.
create or replace function public.gift_claim(p_recipient uuid, p_book_key text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid  uuid := auth.uid();
  v_kind text;
  v_id   uuid;
  v_exp  timestamptz;
begin
  if v_uid is null or p_recipient is null or p_recipient = v_uid
     or coalesce(btrim(p_book_key), '') = '' then
    return jsonb_build_object('ok', false);
  end if;
  -- Serialize claim creation per claimer and per recipient so the
  -- one-active-claim lock and the caps are checked against a stable
  -- world (fixed lock order: claimer, then recipient).
  perform pg_advisory_xact_lock(hashtextextended('gift-claimer:' || v_uid::text, 0));
  perform pg_advisory_xact_lock(hashtextextended('gift-recipient:' || p_recipient::text, 0));
  if not public.gift_has_grant(p_recipient, v_uid) then
    return jsonb_build_object('ok', false);
  end if;
  if not public.gift_pair_linked(p_recipient, v_uid) then
    return jsonb_build_object('ok', false);
  end if;
  if public.gift_pair_blocked(p_recipient, v_uid) then
    return jsonb_build_object('ok', false);
  end if;
  if not public.gift_wishlist_open(p_recipient) then
    return jsonb_build_object('ok', false);
  end if;
  v_kind := public.gift_book_format_kind(p_recipient, p_book_key);
  if v_kind is null then
    return jsonb_build_object('ok', false);
  end if;
  -- One live claim per (recipient, book), whoever holds it.
  if exists (
    select 1 from public.gift_claims c
    where c.recipient_id = p_recipient and c.book_key = p_book_key
      and public.gift_claim_is_live(c.id)
  ) then
    return jsonb_build_object('ok', false);
  end if;
  -- Claimer caps (A2): 2 live claims per recipient, 10 live globally.
  if (select count(*) from public.gift_claims c
      where c.claimer_id = v_uid and c.recipient_id = p_recipient
        and public.gift_claim_is_live(c.id)) >= 2 then
    return jsonb_build_object('ok', false);
  end if;
  if (select count(*) from public.gift_claims c
      where c.claimer_id = v_uid
        and public.gift_claim_is_live(c.id)) >= 10 then
    return jsonb_build_object('ok', false);
  end if;
  insert into public.gift_claims (recipient_id, claimer_id, book_key, format_kind)
  values (p_recipient, v_uid, p_book_key, v_kind)
  returning id, created_at + interval '45 days' into v_id, v_exp;
  return jsonb_build_object('ok', true, 'claim_id', v_id,
                            'format_kind', v_kind, 'expires_at', v_exp);
end;
$$;
revoke all on function public.gift_claim(uuid, text) from public, anon;
grant execute on function public.gift_claim(uuid, text) to authenticated;

-- The granted friends' anonymous view of a recipient's wishlist claims.
-- Refuses the owner by construction; serves nothing at all without the
-- full predicate stack (grant, link, no block, wishlist open). Payload
-- is pinned to book_key + state ONLY (A6) — no claimer, no timestamps,
-- no counts. State served is the single word 'claimed' for live claims.
create or replace function public.gift_claim_states_for(p_recipient uuid)
returns jsonb
language plpgsql
security definer
stable
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is null or p_recipient is null or p_recipient = v_uid then
    return '[]'::jsonb;
  end if;
  if not public.gift_has_grant(p_recipient, v_uid) then return '[]'::jsonb; end if;
  if not public.gift_pair_linked(p_recipient, v_uid) then return '[]'::jsonb; end if;
  if public.gift_pair_blocked(p_recipient, v_uid) then return '[]'::jsonb; end if;
  if not public.gift_wishlist_open(p_recipient) then return '[]'::jsonb; end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object('book_key', t.book_key, 'state', 'claimed')
                     order by t.book_key)
    from (
      select distinct c.book_key
      from public.gift_claims c
      where c.recipient_id = p_recipient
        and public.gift_claim_is_live(c.id)
    ) t
  ), '[]'::jsonb);
end;
$$;
revoke all on function public.gift_claim_states_for(uuid) from public, anon;
grant execute on function public.gift_claim_states_for(uuid) to authenticated;

-- The claimer's own "Gifts you're giving" list. Every claim they have
-- made, with its serve-time composed state (a claim whose grant was
-- revoked reads 'released' here, per spec §6).
create or replace function public.gift_claims_mine()
returns jsonb
language plpgsql
security definer
stable
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is null then return '[]'::jsonb; end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'claim_id', c.id,
             'recipient_id', c.recipient_id,
             'book_key', c.book_key,
             'format_kind', c.format_kind,
             'state', public.gift_claim_state(c.id),
             'created_at', c.created_at,
             'expires_at', c.created_at + interval '45 days')
           order by c.created_at desc)
    from public.gift_claims c
    where c.claimer_id = v_uid
  ), '[]'::jsonb);
end;
$$;
revoke all on function public.gift_claims_mine() from public, anon;
grant execute on function public.gift_claims_mine() to authenticated;

-- The recipient's opt-in view (spec §6, post-review addition): exists
-- only while the caller's own gift_claims_visible setting is ON — with
-- it off this returns the identical empty array as "no claims", so the
-- recipient's default zero-read-path posture is total. Payload: book +
-- claimer + state, never any address data.
create or replace function public.gift_claims_for_recipient()
returns jsonb
language plpgsql
security definer
stable
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is null then return '[]'::jsonb; end if;
  if not coalesce((
    select p.gift_claims_visible from public.profiles p where p.user_id = v_uid
  ), false) then
    return '[]'::jsonb;
  end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'book_key', c.book_key,
             'claimer_id', c.claimer_id,
             'state', 'claimed')
           order by c.book_key)
    from public.gift_claims c
    where c.recipient_id = v_uid
      and public.gift_claim_is_live(c.id)
  ), '[]'::jsonb);
end;
$$;
revoke all on function public.gift_claims_for_recipient() from public, anon;
grant execute on function public.gift_claims_for_recipient() to authenticated;

create or replace function public.gift_mark_purchased(p_claim uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  c     public.gift_claims%rowtype;
begin
  if v_uid is null then return jsonb_build_object('ok', false); end if;
  select * into c from public.gift_claims where id = p_claim;
  if not found or c.claimer_id <> v_uid or c.state <> 'active'
     or not public.gift_claim_is_live(c.id) then
    return jsonb_build_object('ok', false);
  end if;
  update public.gift_claims
     set state = 'purchased', resolved_at = now()
   where id = p_claim;
  return jsonb_build_object('ok', true);
end;
$$;
revoke all on function public.gift_mark_purchased(uuid) from public, anon;
grant execute on function public.gift_mark_purchased(uuid) to authenticated;

create or replace function public.gift_release(p_claim uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
