-- THE reveal. Every predicate is re-evaluated on every call, in the
-- spec's order: (1) the owner's gifting grant to this caller; (2) an
-- accepted circle link; (3) no block in either direction; (4) the
-- owner's sharing toggle on; (5) the caller holds a live claim on one
-- of the owner's wishlist books; (6) the pair budgets — at most 3
-- reveals per claim, at most 10 reveals per (viewer, owner) pair per
-- rolling 30 days, counted from the access log so claim-cycling
-- cannot reset them; (7) the first-pair claim-age rule — a novel
-- pair's first reveal requires the grounding claim to be at least 24
-- hours old; any prior resolved claim between the pair waives it.
-- Field-scoped by the claim's format kind (A4): a print claim reveals
-- the postal fields + phone; an ebook/audio claim reveals ONLY the
-- gift email. Every refusal is the identical empty object {}.
-- A successful reveal is logged at the moment it happens (A5).
create or replace function public.gift_address_reveal(p_owner uuid, p_claim uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  a     public.gift_addresses%rowtype;
  c     public.gift_claims%rowtype;
begin
  if v_uid is null or p_owner is null or p_owner = v_uid then
    return '{}'::jsonb;
  end if;
  -- (1) grant — the base permission underneath every other predicate.
  if not public.gift_has_grant(p_owner, v_uid) then return '{}'::jsonb; end if;
  -- (2) accepted link.
  if not public.gift_pair_linked(p_owner, v_uid) then return '{}'::jsonb; end if;
  -- (3) no block in either direction.
  if public.gift_pair_blocked(p_owner, v_uid) then return '{}'::jsonb; end if;
  -- (4) the owner's sharing toggle.
  select * into a from public.gift_addresses where owner_id = p_owner;
  if not found or not a.sharing_enabled then return '{}'::jsonb; end if;
  -- (5) a live claim, held by this caller, on this owner's books.
  select * into c from public.gift_claims where id = p_claim;
  if not found or c.claimer_id <> v_uid or c.recipient_id <> p_owner
     or not public.gift_claim_is_live(c.id) then
    return '{}'::jsonb;
  end if;
  -- (6) pair budgets (A1), from the append-only log.
  if (select count(*) from public.gift_address_access_log l
      where l.claim_id = c.id) >= 3 then
    return '{}'::jsonb;
  end if;
  if (select count(*) from public.gift_address_access_log l
      where l.viewer_id = v_uid and l.owner_id = p_owner
        and l.revealed_at > now() - interval '30 days') >= 10 then
    return '{}'::jsonb;
  end if;
  -- (7) first-pair claim age (A3).
  if not exists (
    select 1 from public.gift_claims pc
    where pc.recipient_id = p_owner and pc.claimer_id = v_uid
      and pc.id <> c.id
      and (pc.resolved_at is not null
           or pc.created_at + interval '45 days' <= now())
  ) and c.created_at > now() - interval '24 hours' then
    return '{}'::jsonb;
  end if;
  insert into public.gift_address_access_log (viewer_id, owner_id, claim_id)
  values (v_uid, p_owner, c.id);
  if c.format_kind = 'print' then
    return jsonb_build_object(
      'kind', 'print',
      'name',    public.gift_dec(a.name_enc, p_owner),
      'street',  public.gift_dec(a.street_enc, p_owner),
      'city',    public.gift_dec(a.city_enc, p_owner),
      'region',  public.gift_dec(a.region_enc, p_owner),
      'postal',  public.gift_dec(a.postal_enc, p_owner),
      'country', public.gift_dec(a.country_enc, p_owner),
      'phone',   public.gift_dec(a.phone_enc, p_owner)
    );
  end if;
  return jsonb_build_object(
    'kind', c.format_kind,
    'email', public.gift_dec(a.email_enc, p_owner)
  );
end;
$$;
revoke all on function public.gift_address_reveal(uuid, uuid) from public, anon;
grant execute on function public.gift_address_reveal(uuid, uuid) to authenticated;

-- The owner's two-tier view of the access log (A5), enforced here:
-- nothing younger than 72 hours is returned at all (fact tier: the
-- timestamp, with claimer and book still null); detail (viewer + book)
-- appears once the claim has resolved or the reveal is 14 days old,
-- whichever comes first. Admins read the log immediately through the
-- table's admin policy instead.
create or replace function public.gift_address_log_mine()
returns jsonb
language plpgsql
security definer
stable
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is null then return '[]'::jsonb; end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'revealed_at', l.revealed_at,
             'viewer_id', case when c.resolved_at is not null
                                 or l.revealed_at <= now() - interval '14 days'
                               then l.viewer_id end,
             'book_key',  case when c.resolved_at is not null
                                 or l.revealed_at <= now() - interval '14 days'
                               then c.book_key end)
           order by l.revealed_at desc)
    from public.gift_address_access_log l
    join public.gift_claims c on c.id = l.claim_id
    where l.owner_id = v_uid
      and l.revealed_at <= now() - interval '72 hours'
  ), '[]'::jsonb);
end;
$$;
revoke all on function public.gift_address_log_mine() from public, anon;
grant execute on function public.gift_address_log_mine() to authenticated;

