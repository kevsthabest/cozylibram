-- v581: Gift a Book v1 — wishlist purchasing & gifting (spec:
-- docs/gift-purchase-spec.md, approved 2026-10-15). Tagless retailer deep
-- links are client-side; everything in this migration is the coordination
-- and PII layer: per-friend gifting grants, secret claims, and the
-- encrypted gift-address vault.
--
-- Shapes, all following the v574 Marginalia precedent:
--   * gift_claims / gift_address_access_log: zero-policy tables (admin
--     SELECT via is_admin() only); every user path is a SECURITY DEFINER
--     RPC that composes its predicates at call time.
--   * gift_addresses: owner-only RLS (owner SELECT of their own row);
--     writes and all decrypted reads go through definer RPCs, so the
--     encrypted columns are the only form the data ever takes at rest
--     or in transit to any client.
--   * gift_grants: recipient-managed rows (recipient_id = auth.uid());
--     absence of a row IS the default (grant OFF for every friendship).
--
-- Encryption (spec A8, do it now): address / email / phone are stored
-- ONLY as pgsodium AEAD-IETF ciphertext (nonce packed as the first 24
-- bytes of each value, plaintext bound by additional data to the owner
-- id), under a key created here and held by pgsodium in Supabase Vault.
-- No key material appears in this file, the repo, or any client.
--
-- APPLY NOTE (one manual step, Supabase's documented TCE provisioning):
-- pgsodium's by-key-id crypto functions require the executing role to
-- hold the pgsodium_keyiduser role, which the migration role cannot
-- grant itself (verified live 2026-10-15: no project role holds it and
-- postgres has no ADMIN option on it). Run once, from the Supabase
-- dashboard SQL editor, alongside this migration:
--     grant pgsodium_keyiduser to postgres;
-- Until that grant lands, gift_enc/gift_dec raise a permission error —
-- the client fails closed on any gift RPC error, so the feature simply
-- stays invisible rather than degrading to plaintext anywhere.
--
-- Serve-time composition (spec A7): a stored claim row is never the
-- truth by itself. gift_claim_is_live() re-derives liveness on every
-- read: stored state, 45-day expiry, grant in force, accepted link, no
-- block, wishlist not hidden, and the recipient still holding the book
-- in the wishlist derivation (or as a trophy want). Every surface —
-- friends' states, the claimer's list, the reveal gate — reads through
-- it, so revocation / blocking / link loss / self-purchase release the
-- book instantly with no cleanup pass, and re-granting never resurrects
-- a claim whose stored state has resolved.
--
-- Refusal discipline (spec §6/§7 + A10): gift_claim returns the
-- identical {ok:false} for every refusal cause; gift_address_reveal
-- returns the identical empty object {} for every refusal cause. No
-- error shape distinguishes grant, link, block, toggle, claim, budget,
-- or claim-age causes.

begin;

