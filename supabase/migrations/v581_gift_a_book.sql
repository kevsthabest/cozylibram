-- ====================== internal helpers ======================
-- None of these are granted to any client role; they exist to be
-- composed inside the definer RPCs below (and the test suite pins that
-- every one of them is revoked from public / anon / authenticated).

-- AEAD-IETF encrypt under the vault-held gift key. The nonce (24 bytes,
-- CSPRNG) is packed as the value's first 24 bytes; the plaintext is
-- bound to the owner by additional data, so a ciphertext copied onto
-- another owner's row decrypts to nothing.
create or replace function public.gift_enc(p_plain text, p_owner uuid)
returns bytea
language plpgsql
security definer
stable
set search_path = public
as $$
declare
  v_key   uuid;
  v_nonce bytea := gen_random_bytes(24);
begin
  if p_plain is null then return null; end if;
  select key_id into v_key from public.gift_crypto where id = 1;
  return v_nonce || pgsodium.crypto_aead_ietf_encrypt(
    convert_to(p_plain, 'UTF8'),
    convert_to(p_owner::text || ':gift-address-v1', 'UTF8'),
    v_nonce, v_key);
end;
$$;
revoke all on function public.gift_enc(text, uuid) from public, anon, authenticated;

create or replace function public.gift_dec(p_packed bytea, p_owner uuid)
returns text
language plpgsql
security definer
stable
set search_path = public
as $$
declare
  v_key uuid;
begin
  if p_packed is null then return null; end if;
  select key_id into v_key from public.gift_crypto where id = 1;
  return convert_from(pgsodium.crypto_aead_ietf_decrypt(
    substring(p_packed from 25),
    convert_to(p_owner::text || ':gift-address-v1', 'UTF8'),
    substring(p_packed from 1 for 24), v_key), 'UTF8');
end;
$$;
revoke all on function public.gift_dec(bytea, uuid) from public, anon, authenticated;

