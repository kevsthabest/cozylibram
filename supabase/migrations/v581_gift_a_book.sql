  id     int primary key check (id = 1),
  key_id uuid not null
);
alter table public.gift_crypto enable row level security;
revoke all on public.gift_crypto from anon, authenticated;
insert into public.gift_crypto (id, key_id)
  select 1, k.id from pgsodium.valid_key k where k.name = 'gift-address-v1'
  on conflict (id) do nothing;
insert into public.gift_crypto (id, key_id)
  select 1, (pgsodium.create_key(name := 'gift-address-v1')).id
  where not exists (select 1 from public.gift_crypto where id = 1)
  on conflict (id) do nothing;

